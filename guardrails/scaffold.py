from __future__ import annotations

import ast
import json
import shutil
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import yaml

from guardrails.integrations import builtin_tool_security, harness_tools, install_hooks, runtime_policy

WRITE_WORDS = ("write", "delete", "remove", "create", "update", "send", "post", "run", "exec", "deploy")


@dataclass(frozen=True)
class DiscoveredTool:
    name: str
    description: str
    args: dict[str, dict[str, Any]]
    source: str
    output_trust: str = "trusted"

    @property
    def effect(self) -> str:
        text = f"{self.name} {self.description}".lower()
        return "write" if any(word in text for word in WRITE_WORDS) else "read"


def discover_tools(target: Path) -> list[DiscoveredTool]:
    discovered: dict[str, DiscoveredTool] = {}
    excluded = {".git", ".venv", "venv", "node_modules", "guardrails"}
    for path in target.rglob("*"):
        if any(part in excluded or part.startswith(".") for part in path.relative_to(target).parts):
            continue
        tools: list[DiscoveredTool] = []
        if path.suffix == ".py":
            tools = _from_python(path, target)
        elif path.suffix == ".json":
            tools = _from_json(path, target)
        for tool in tools:
            discovered.setdefault(tool.name, tool)
    return sorted(discovered.values(), key=lambda item: item.name)


def scaffold(target: Path, *, force: bool = False, harness: str = "generic") -> list[str]:
    target = target.resolve()
    if not target.is_dir():
        raise FileNotFoundError(f"target is not a directory: {target}")
    tools = discover_tools(target)
    if harness != "generic":
        tools = _merge_tools(tools, _harness_tools(harness))
    destinations = [
        *([target / "guardrails"] if harness == "generic" else []),
        target / "tools.yaml",
        target / "sandbox.yaml",
        target / "THREAT-MODEL.md",
    ]
    existing = [path for path in destinations if path.exists()]
    if existing and not force:
        names = ", ".join(path.name for path in existing)
        raise FileExistsError(f"refusing to overwrite: {names}; pass --force")
    package_root = Path(__file__).resolve().parent.parent
    if harness == "generic":
        _vendor_toolkit(target / "guardrails")
    policy = {
        "version": 1,
        "runtime": runtime_policy(
            harness,
            [tool.name for tool in tools if tool.source.endswith(" built-in")],
        ),
        "tools": {tool.name: _tool_policy(tool) for tool in tools},
    }
    (target / "tools.yaml").write_text(yaml.safe_dump(policy, sort_keys=False), encoding="utf-8")
    shutil.copy2(package_root / "templates" / "sandbox.yaml", target / "sandbox.yaml")
    threat_template = (package_root / "templates" / "THREAT-MODEL.md").read_text(encoding="utf-8")
    legs = _trifecta(tools)
    threat = threat_template.replace(
        "{{PRIVATE_DATA}}", "yes (inferred, review)" if legs[0] else "no (inferred, review)"
    )
    threat = threat.replace("{{UNTRUSTED_CONTENT}}", "yes (inferred, review)" if legs[1] else "no (inferred, review)")
    threat = threat.replace(
        "{{EXTERNAL_COMMUNICATION}}", "yes (inferred, review)" if legs[2] else "no (inferred, review)"
    )
    threat = threat.replace("{{TRIFECTA_COUNT}}", str(sum(legs)))
    threat = threat.replace("{{RESIDUAL_RISK}}", "TODO")
    threat = threat.replace("{{EXTERNAL_CONTROLS}}", "TODO")
    (target / "THREAT-MODEL.md").write_text(threat, encoding="utf-8")
    hook_paths = install_hooks(target, harness)
    writes = sum(tool.effect == "write" for tool in tools)
    unresolved = sum(not tool.source.endswith(" built-in") for tool in tools)
    actions = [
        f"Review {writes} tools inferred as effect: write; effect inference is only a draft.",
        f"Resolve TODO scope and reversible fields on {unresolved} discovered tools.",
    ]
    if hook_paths:
        actions.append(f"Review the installed {harness} hook and run one denied test call.")
    else:
        actions.append("Wire ExecutionGateway into the executor. See docs/ADOPT.md.")
    return actions


def _vendor_toolkit(destination: Path) -> None:
    if destination.exists():
        if not (destination / ".pehredaar-generated").exists():
            raise FileExistsError("refusing to replace guardrails/: missing Pehredaar generated marker")
        shutil.rmtree(destination)
    shutil.copytree(Path(__file__).resolve().parent, destination, ignore=shutil.ignore_patterns("__pycache__", "*.pyc"))
    (destination / ".pehredaar-generated").write_text("generated by pehredaar\n", encoding="utf-8")


def _from_python(path: Path, root: Path) -> list[DiscoveredTool]:
    try:
        tree = ast.parse(path.read_text(encoding="utf-8"))
    except (SyntaxError, UnicodeDecodeError):
        return []
    tools: list[DiscoveredTool] = []
    for node in tree.body:
        if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) or node.name.startswith("_"):
            continue
        decorators = {_decorator_name(item) for item in node.decorator_list}
        typed = bool(node.args.args) and all(argument.annotation is not None for argument in node.args.args)
        is_tool = bool(decorators & {"tool", "function_tool", "mcp.tool"}) or (typed and node.returns is not None)
        if not is_tool:
            continue
        args = {
            argument.arg: {"type": _annotation_type(argument.annotation), "required": True}
            for argument in node.args.args
            if argument.arg not in {"self", "cls"}
        }
        tools.append(DiscoveredTool(node.name, ast.get_docstring(node) or "", args, str(path.relative_to(root))))
    return tools


def _from_json(path: Path, root: Path) -> list[DiscoveredTool]:
    try:
        raw = json.loads(path.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, UnicodeDecodeError):
        return []
    candidates = raw.get("tools", raw) if isinstance(raw, dict) else raw
    if not isinstance(candidates, list):
        return []
    tools: list[DiscoveredTool] = []
    for item in candidates:
        if not isinstance(item, dict):
            continue
        function = item.get("function", item)
        if not isinstance(function, dict) or not isinstance(function.get("name"), str):
            continue
        schema = function.get("parameters", function.get("inputSchema", {}))
        properties = schema.get("properties", {}) if isinstance(schema, dict) else {}
        required = set(schema.get("required", ())) if isinstance(schema, dict) else set()
        args = {
            name: {"type": _json_type(value.get("type", "string")), "required": name in required}
            for name, value in properties.items()
            if isinstance(value, dict)
        }
        tools.append(
            DiscoveredTool(function["name"], str(function.get("description", "")), args, str(path.relative_to(root)))
        )
    return tools


def _tool_policy(tool: DiscoveredTool) -> dict[str, Any]:
    builtin = tool.source.endswith(" built-in")
    reversible: bool | str
    if builtin:
        scope, reversible, approval = builtin_tool_security(tool.name)
    else:
        scope = "TODO"
        reversible = "TODO"
        approval = "when_tainted" if tool.effect == "write" else "never"
    return {
        "effect": tool.effect,
        "args": tool.args,
        "scope": scope,
        "reversible": reversible,
        "approval": approval,
        "source": tool.source,
        "output_trust": tool.output_trust,
    }


def _merge_tools(discovered: list[DiscoveredTool], builtins: list[DiscoveredTool]) -> list[DiscoveredTool]:
    merged = {tool.name: tool for tool in builtins}
    merged.update({tool.name: tool for tool in discovered})
    return sorted(merged.values(), key=lambda item: item.name)


def _harness_tools(harness: str) -> list[DiscoveredTool]:
    source = f"{harness} built-in"
    return [DiscoveredTool(name, text, args, source, trust) for name, text, args, trust in harness_tools(harness)]


def _decorator_name(node: ast.expr) -> str:
    if isinstance(node, ast.Call):
        return _decorator_name(node.func)
    if isinstance(node, ast.Name):
        return node.id
    if isinstance(node, ast.Attribute):
        return f"{_decorator_name(node.value)}.{node.attr}"
    return ""


def _annotation_type(node: ast.expr | None) -> str:
    name = ast.unparse(node) if node is not None else "str"
    return {"int": "integer", "float": "number", "bool": "boolean", "Path": "path"}.get(name, "string")


def _json_type(value: str) -> str:
    return {"integer": "integer", "number": "number", "boolean": "boolean"}.get(value, "string")


def _trifecta(tools: list[DiscoveredTool]) -> tuple[bool, bool, bool]:
    text = " ".join(f"{tool.name} {tool.description}" for tool in tools).lower()
    private = any(word in text for word in ("secret", "credential", "private", "file", "database"))
    untrusted = any(word in text for word in ("issue", "email", "web", "fetch", "input", "mcp"))
    external = any(word in text for word in ("http", "send", "post", "publish", "export", "comment"))
    return private, untrusted, external


